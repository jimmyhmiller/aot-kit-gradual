import assert from "node:assert/strict";
import test from "node:test";
import { buildObjectLayouts, extractMakeBasicObjectInputs,
  extractOrdinaryCreateFromConstructorInputs, renderObjectLayoutJsl,
  renderObjectLayoutRuntime } from "./object-layouts.mjs";

function manifest() {
  return { schemaVersion: 1,
    slots: [
      { name: "PrivateElements", storage: "spec-list", traced: true },
      { name: "Prototype", storage: "js-value", traced: true },
      { name: "Extensible", storage: "boolean", traced: false },
    ],
    essentialMethods: [{ name: "GetPrototypeOf" }, { name: "DefineOwnProperty" }],
    activeDispatchMethods: ["GetPrototypeOf", "DefineOwnProperty"],
    methodFamilies: [{ name: "OrdinaryObjectMethods", overrides: [] }],
    makeBasicObjectInputs: [
      { name: "OrdinaryObjectBase", slots: ["Prototype", "Extensible"], methods: "OrdinaryObjectMethods" },
    ] };
}

test("MakeBasicObject layouts append the mandatory private-elements slot deterministically", () => {
  const generated = buildObjectLayouts(manifest());
  assert.deepEqual(generated.layouts[0].slots, ["Prototype", "Extensible", "PrivateElements"]);
  assert.deepEqual(generated.layouts[0].slotIds, [2, 3, 1]);
  assert.match(generated.layouts[0].fingerprint, /^[0-9a-f]{64}$/);
  assert.deepEqual(buildObjectLayouts(manifest()), generated);
});

test("layout inputs generate canonical zero-width JSL slot-list declarations", () => {
  assert.equal(renderObjectLayoutJsl(buildObjectLayouts(manifest())),
    `; GENERATED by tools/object-layouts.mjs from spec/object-layouts.json. DO NOT EDIT.
; These are specification-pinned internal-slot Lists accepted by object creation operations.
; PrivateElements is deliberately absent: ordinary object creation appends it exactly once.

(internal-method-family OrdinaryObjectMethods)

(internal-method GetPrototypeOf)
(internal-method DefineOwnProperty)

(macro UsesOrdinaryGetPrototypeOf :params [(object dyn)] :ret bool (object-method-is-ordinary object GetPrototypeOf))
(macro UsesOrdinaryDefineOwnProperty :params [(object dyn)] :ret bool (object-method-is-ordinary object DefineOwnProperty))

(internal-slot PrivateElements spec-list)
(internal-slot Prototype js-value)
(internal-slot Extensible boolean)

(slot-list OrdinaryObjectBase [Prototype Extensible])
`);
});

test("runtime descriptors share manifest slot ids, order, storage kinds, and method family", () => {
  const header = renderObjectLayoutRuntime(buildObjectLayouts(manifest()));
  assert.match(header, /AOT_INTERNAL_SLOT_PRIVATE_ELEMENTS 1/);
  assert.match(header, /aot_layout_1_slots\[\] = \{ 2, 3, 1 \}/);
  assert.match(header, /AOT_SLOT_JS_VALUE, AOT_SLOT_BOOLEAN, AOT_SLOT_SPEC_LIST/);
  assert.match(header, /AOT_METHOD_FAMILY_ORDINARY_OBJECT_METHODS 1/);
  assert.match(header, /AOT_METHOD_FAMILY_COUNT 1/);
  assert.match(header, /\{ 1, 3, 1, aot_layout_1_slots, aot_layout_1_storage \}/);
});

test("generated per-method bitsets encode only a family's declared overrides", () => {
  const input = manifest();
  input.methodFamilies.push({ name: "ArrayExoticMethods", overrides: ["DefineOwnProperty"] });
  const header = renderObjectLayoutRuntime(buildObjectLayouts(input));
  assert.match(header, /UINT64_C\(0x0\), \/\* OrdinaryObjectMethods \*\//);
  assert.match(header, /UINT64_C\(0x2\), \/\* ArrayExoticMethods \*\//);
});

test("the pinned-source inventory extracts concrete slot lists and rejects manifest drift", () => {
  const source = `MakeBasicObject(_internalSlotsList_) MakeBasicObject(« [[Prototype]], [[Extensible]] »)`;
  const inputs = extractMakeBasicObjectInputs(source);
  assert.deepEqual(inputs, [["Prototype", "Extensible"]]);
  assert.equal(buildObjectLayouts(manifest(), inputs).pinnedMakeBasicObjectInputs.length, 1);
  assert.throws(() => buildObjectLayouts(manifest(), [["Prototype"]]), /undeclared MakeBasicObject input/);
});

test("OrdinaryCreateFromConstructor layouts are pinned separately from MakeBasicObject", () => {
  const source = `OrdinaryCreateFromConstructor(NewTarget, *"%DataView.prototype%"*,
    « [[DataView]], [[ViewedArrayBuffer]], [[ByteLength]], [[ByteOffset]] »)`;
  const inputs = extractOrdinaryCreateFromConstructorInputs(source);
  assert.deepEqual(inputs, [["Prototype", "Extensible", "DataView", "ViewedArrayBuffer",
    "ByteLength", "ByteOffset"]]);
  const input = manifest();
  input.slots.push(
    { name: "DataView", storage: "boolean", traced: false },
    { name: "ViewedArrayBuffer", storage: "js-value", traced: true },
    { name: "ByteLength", storage: "js-value", traced: true },
    { name: "ByteOffset", storage: "js-value", traced: true });
  input.makeBasicObjectInputs.push({ name: "DataViewObjectBase",
    slots: inputs[0], methods: "OrdinaryObjectMethods",
    creation: "OrdinaryCreateFromConstructor" });
  assert.doesNotThrow(() => buildObjectLayouts(input,
    [["Prototype", "Extensible"]], inputs));
  assert.throws(() => buildObjectLayouts(input,
    [["Prototype", "Extensible"]], []), /no pinned OrdinaryCreateFromConstructor/);
});

test("layout validation rejects unknown, duplicate, and caller-supplied mandatory slots", () => {
  const unknown = manifest(); unknown.makeBasicObjectInputs[0].slots.push("Missing");
  assert.throws(() => buildObjectLayouts(unknown), /unknown slot Missing/);
  const duplicate = manifest(); duplicate.makeBasicObjectInputs[0].slots.push("Prototype");
  assert.throws(() => buildObjectLayouts(duplicate), /duplicate slot Prototype/);
  const privateSlot = manifest(); privateSlot.makeBasicObjectInputs[0].slots.push("PrivateElements");
  assert.throws(() => buildObjectLayouts(privateSlot), /appended by MakeBasicObject/);
});

test("layout validation rejects invalid storage and method-family contracts", () => {
  const storage = manifest(); storage.slots[1].storage = "pointer";
  assert.throws(() => buildObjectLayouts(storage), /invalid storage kind/);
  const tracing = manifest(); tracing.slots[2].traced = true;
  assert.throws(() => buildObjectLayouts(tracing), /boolean storage must be untraced/);
  const methods = manifest(); methods.makeBasicObjectInputs[0].methods = "ProxyMethods";
  assert.throws(() => buildObjectLayouts(methods), /unknown method family/);
  const unknownOverride = manifest(); unknownOverride.methodFamilies[0].overrides.push("Delete");
  assert.throws(() => buildObjectLayouts(unknownOverride), /unknown essential method Delete/);
  const duplicateOverride = manifest(); duplicateOverride.methodFamilies.push(
    { name: "StringExoticMethods", overrides: ["GetPrototypeOf", "GetPrototypeOf"] });
  assert.throws(() => buildObjectLayouts(duplicateOverride), /duplicate override GetPrototypeOf/);
  const unknownActive = manifest(); unknownActive.activeDispatchMethods.push("Delete");
  assert.throws(() => buildObjectLayouts(unknownActive), /unknown active dispatch method Delete/);
  const duplicateActive = manifest(); duplicateActive.activeDispatchMethods.push("GetPrototypeOf");
  assert.throws(() => buildObjectLayouts(duplicateActive), /duplicate active dispatch method GetPrototypeOf/);
});
